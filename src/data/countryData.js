/**
 * Resolves TopoJSON feature to country details
 */
export function getCountryByFeature(feature) {
  if (!feature) return null;

  // 1. Try numeric ID
  const featId = feature.id ? feature.id.toString() : null;
  if (featId && COUNTRY_BY_NUMERIC[featId]) {
    return COUNTRY_BY_NUMERIC[featId];
  }

  // 2. Try Name fallback
  const featName = feature.properties ? feature.properties.name : null;
  if (featName && NAME_FALLBACKS[featName]) {
    return NAME_FALLBACKS[featName];
  }

  // 3. Direct Code match if feature has code
  if (feature.properties && feature.properties.code && COUNTRY_BY_CODE[feature.properties.code]) {
    return COUNTRY_BY_CODE[feature.properties.code];
  }

  if (featName) {
    return {
      nameKo: featName,
      code: 'UN',
      flag: '🌐',
      aliases: [featName]
    };
  }

  return null;
}

/**
 * Helper to search countries by Korean name, English code, or alias
 */
export function searchCountries(query) {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();

  return COUNTRY_LIST.filter(item => {
    if (item.nameKo.toLowerCase().includes(q)) return true;
    if (item.code.toLowerCase().includes(q)) return true;
    if (item.aliases.some(a => a.toLowerCase().includes(q))) return true;
    return false;
  });
}
